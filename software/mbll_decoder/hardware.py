# -*- coding: utf-8 -*-
"""MBLL 解码器的配置 —— **与 SRS 侧、与 config.py 都不共享**。

架构依据（`docs/双解码器架构.md` §三「隔离规则」）：
    配置不共享。波长集、距离、滤波参数各自独立演进，
    否则改一边会悄悄影响另一边，失去「可分别调试」。

本模块**刻意不 import `config`**：
    `config.py` 描述的是现役 MBLL 产品线（850/810/770/730/700、D2=1.0 cm 短距），
    与本硬件不是同一台机器。`fnirs_pipeline/mbll.py` 耦合在它上面，
    故本解码器另起，只复用 `fnirs_pipeline.mbll_core` 里的纯函数
    （消光系数表、DPF 公式、ΔOD 换算）—— 那些是物理常数与无状态计算，
    属于「可共享」的一类。
"""

from __future__ import annotations

import numpy as np

# ---------------------------------------------------------------------------
# 波长
# ---------------------------------------------------------------------------
# 只能用 670/770。810/850/950 带与体模光学性质无关的加性伪信号
# （2026-10-22 实测：C2 块上 810@4cm 读数的 77.5% 不是穿过体模的光），
# 加性项在 ΔOD = −log10(I_t/I_ref) 的比值里**不会消掉**，会压缩 ΔHb 幅度。
#
# 代价：条件数 7.80（产品线五波长 3.81）。HbO 噪声差约 2 倍，HbR 略好
# —— 后者是 670 的功劳，它的 HbO/HbR 消光比 0.140，是全部波长里离
# 等吸收点最远的。
WAVELENGTHS_NM = np.array([670.0, 770.0])

# ---------------------------------------------------------------------------
# 距离
# ---------------------------------------------------------------------------
# MBLL 只需**单个**距离（与 SRS 需要两个距离算斜率相反）。
# 取 3.0 cm：信噪比远好于 4.0 cm（在体 4cm 常出现非正读数）。
# 4.0 cm 可另出一路独立的、采样更深的估计，但噪声大得多。
DISTANCE_CM = 3.0
DISTANCE_DEEP_CM = 4.0

# 无短距通道 → **SSR（短距回归去头皮）不可用**。
# 注：`config.py:75` 显示产品线自己也已定版不用 SSR。
HAS_SHORT_SEPARATION = False

# ---------------------------------------------------------------------------
# 带通
# ---------------------------------------------------------------------------
# 上限 0.05 Hz 是**实测定的**，不是沿用 fNIRS 惯例的 0.1 Hz：
#
#   2026-10-22 的 10 分钟体模静置数据显示，噪声主成分是
#   **0.0868 Hz 的窄带干扰**（暗时隙里也有，电路/环境来源）。
#   它正落在原定的 0.01~0.1 Hz 带内（实测展宽 0.075~0.100 Hz）。
#
#   各上限下实测（干扰带 = 0.075~0.100 Hz，分母是 ΔHbO 输出总功率，
#   故含滤波器滚降泄漏）：
#
#       上限    ΔHbO std    干扰带占输出    相对 0.05
#       0.03    0.0685 µM      0.00%         0.55×
#       0.05    0.1238 µM      0.00%         1.00×   ← 取此
#       0.07    0.1476 µM      0.68%         1.19×
#       0.10    0.1858 µM     21.00%         1.50×   ← 原定值，不可用
#
#   不取更低的 0.03：去饱和事件是几十秒量级，0.03 Hz（33 s）会切掉快的一半。
#   0.05 是「干扰占比仍为 0」前提下能取到的上限（0.0868/0.05 = 1.74 倍频程，
#   4 阶 Butterworth 约 84 倍功率衰减）。
#
#   代价：Mayer 波（~0.1 Hz）一并滤掉。但它本就被该干扰污染，损失有限。
#
# ⚠️ 奈奎斯特只有 0.33 Hz（扫描速率实测 0.657 周期/秒），
#    呼吸（0.2~0.3 Hz）贴边、心搏（0.8~2 Hz）完全混叠 —— 都测不到。
BP_LOW_HZ = 0.01
BP_HIGH_HZ = 0.05
BP_ORDER = 4

# 高通截止 fc 的瞬态特征时间约 1/fc，需约 3 倍才衰减干净。
# 0.01 Hz → 至少 300 秒记录。短于此拒绝出结果，而不是给个看着像样的数。
MIN_RECORD_S = 3.0 / BP_LOW_HZ

# ---------------------------------------------------------------------------
# DPF
# ---------------------------------------------------------------------------
# 用 `mbll_core.get_dpf`（Scholkmann & Wolf 2013 的参数化式）。
# ⚠️ 原文标定区间 **690~832 nm**：
#       670 nm 是**外推 20 nm**，可接受但须记录在案
#       850 nm 外推 18 nm
#       950 nm **公式给出负值 −0.128，绝对不可用**
DEFAULT_AGE = 30.0
DPF_VALID_NM = (690.0, 832.0)

# ---------------------------------------------------------------------------
# 细胞色素
# ---------------------------------------------------------------------------
# ⚠️ 两个问题，故**当前跳过 Cyt**：
#   ① 2 个波长解 HbO/HbR 两个未知数已是恰定，Cyt 在数学上**不可解**
#   ② 下表（誊自 config.py，单位同源）**没有 670 nm 条目**，
#      本仓库也没有可引的出处 —— 不编造。
# 表保留在此是为了将来 810/850 修好、恢复到 ≥3 波长时直接可用；
# 届时若仍要用 670，必须先补上它的差分消光系数并注明出处。
CYT_DIFFERENCE_EXTINCTION = {
    700.0: 2.4148076,
    730.0: 1.8012364,
    770.0: 1.9650957,
    810.0: 2.3166136,
    850.0: 2.2899045,
}


def cyt_solvable(wavelengths) -> bool:
    """Cyt 是否可解：波长数 ≥3（否则恰定）且每一路都有表项。"""
    wl = [float(w) for w in wavelengths]
    return len(wl) >= 3 and all(w in CYT_DIFFERENCE_EXTINCTION for w in wl)


def dpf_note(wavelengths) -> list[str]:
    """哪些波长的 DPF 是外推的 —— 调用方应把这些话带进输出。"""
    lo, hi = DPF_VALID_NM
    out = []
    for w in (float(x) for x in wavelengths):
        if not (lo <= w <= hi):
            d = lo - w if w < lo else w - hi
            out.append(f"{w:.0f}nm 的 DPF 是外推 {d:.0f}nm"
                       f"（Scholkmann 2013 标定区间 {lo:.0f}~{hi:.0f}）")
    return out
