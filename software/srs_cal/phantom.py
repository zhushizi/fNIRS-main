# ---------------------------------------------------------------------------
# 光谱模型
# ---------------------------------------------------------------------------
def fit_musp_powerlaw(wl, musp):
    """μs′(λ) = a·(λ/800)^(−b)，对数域线性拟合。返回 (a, b)。

    Mie 散射的标准参数化。4 个认证点拟 2 个参数，留一验证见下。
    """
    p = np.polyfit(np.log(np.asarray(wl, float) / 800.0),
                   np.log(np.asarray(musp, float)), 1)
    return float(np.exp(p[1])), float(-p[0])


def eval_musp(a: float, b: float, wl) -> np.ndarray:
    return a * (np.asarray(wl, float) / 800.0) ** (-b)


def fit_mua_linear(wl, mua):
    """μa(λ) 用【一次】多项式拟合。

    ⚠️⚠️ **不要改成二次。** 本体模的 μa 谱很平（全谱变化仅约 10%），
       而认证不确定度已有 1.7~2.2%。4 个点拟 3 个参数等于在拟噪声 ——
       实测留一误差（12 块中位）：

           留出波长   一次      二次
             685     5.76%    74.77%
             808     5.80%     6.58%
             830     3.07%     7.29%
             975     4.56%   115.45%

       二次在两个端点直接崩掉，而 670 nm 恰恰需要外推到 685 以下。
    """
    return np.polyfit(np.asarray(wl, float) / 800.0, np.asarray(mua, float), 1)


def eval_mua(coef, wl) -> np.ndarray:
    return np.polyval(coef, np.asarray(wl, float) / 800.0)


# ---------------------------------------------------------------------------
# 插值到器件波长
# ---------------------------------------------------------------------------
def interpolate_to(wavelengths_nm) -> tuple[np.ndarray, np.ndarray]:
    """把 12 块的认证 μa/μs′ 插到给定波长。

    返回 (mua, musp)，形状均为 (12, n_wl)。
    """
    wl = np.asarray(wavelengths_nm, float)
    mua = np.zeros((len(BLOCK_CODES), wl.size))
    musp = np.zeros((len(BLOCK_CODES), wl.size))
    for i in range(len(BLOCK_CODES)):
        a, b = fit_musp_powerlaw(CERT_WL_NM, MUSP_CERT[i])
        musp[i] = eval_musp(a, b, wl)
        mua[i] = eval_mua(fit_mua_linear(CERT_WL_NM, MUA_CERT[i]), wl)
    return mua, musp


def loocv_error() -> dict[float, tuple[float, float]]:
    """对 4 个认证点做留一交叉验证，估计插值误差。

    返回 {波长: (μa 相对误差中位, μs′ 相对误差中位)}。
    这是本标定方案误差地板的**实测依据**，不是估计值。
    """
    out: dict[float, tuple[float, float]] = {}
    for j, w in enumerate(CERT_WL_NM):
        keep = [k for k in range(CERT_WL_NM.size) if k != j]
        ea, es = [], []
        for i in range(len(BLOCK_CODES)):
            a, b = fit_musp_powerlaw(CERT_WL_NM[keep], MUSP_CERT[i][keep])
            es.append(abs(eval_musp(a, b, w) / MUSP_CERT[i][j] - 1))
            c = fit_mua_linear(CERT_WL_NM[keep], MUA_CERT[i][keep])
            ea.append(abs(eval_mua(c, w) / MUA_CERT[i][j] - 1))
        out[float(w)] = (float(np.median(ea)), float(np.median(es)))
    return out


def interpolation_mode(wl_nm: float) -> str:
    """该波长是内插还是外推 —— 外推的不确定度显著更大。"""
    return "内插" if CERT_WL_NM.min() <= wl_nm <= CERT_WL_NM.max() else "外推"
