# ⚠️ **950 nm 不进 SRS 反演**，只保留为质量/含水量参考通道。
#
#    依据是**在体实测**，不是文献估算 —— 取 10 名成人前额的时域 DOS 实测
#    μa(λ)（Zenodo 10.5281/zenodo.15828014，CC-BY 4.0），用本器件的四个
#    波长 670/770/810/850 拟纯 HbO/HbR 模型（与实际反演完全一致的配置），
#    再看各波长的残差 =（实测 − 纯血红蛋白预测）/ 实测：
#
#        670 nm   −0.1% ± 0.4%
#        770 nm   +0.3% ± 1.3%
#        810 nm   −0.5% ± 0.7%
#        850 nm   +0.2% ± 0.5%
#        950 nm  **+40.0% ± 2.5%**   ← 带外
#
#    四个在用波长上纯血红蛋白模型几乎完美（|残差| 均值 0.7%），
#    而 950 nm 有 40% 的吸收不是血红蛋白贡献（水 + 脂质）。
#
#    直接后果：同一批人、同一张消光表，
#        四波长 670/770/810/850        → SO₂ = 77.6 ± 3.6 %
#        五波长（加 950）              → SO₂ = 87.2 ± 3.1 %
#    **加入 950 使 SO₂ 偏高 +9.6 %O₂。**
#
#    `fnirs_pipeline/srs.py` 的 compute_toi() 文档串记录了同一机理：
#    「水与脂质吸收未建模…970nm 处水峰使 μa 从 0.157 升到 0.377」。
#
#    体模是干材料、不含水，950 nm 在体模上照常可测，采集时一并存档备查。
WAVELENGTHS_ALL_NM = np.array([670.0, 770.0, 810.0, 850.0, 950.0])
WAVELENGTHS_NM = np.array([670.0, 770.0, 810.0, 850.0])      # 设计上进反演的四路
WL_REFERENCE_ONLY_NM = np.array([950.0])                      # 仅作参考，不反演

# ---------------------------------------------------------------------------
# 810 nm：曾停用，2026-10-10 **恢复**
# ---------------------------------------------------------------------------
# 停用的原因后来证明是**误判**，记在这里以免重蹈。
#
# 当时（旧固件，无暗时隙）810 的 4cm 读数比"应有值"多 2.1~7.5 倍，
# 并据此排除了体模、几何、环境光、固件串台、解析错误，断定是硬件光路泄漏。
# **那个结论错了。** 真正的病因是**暗电平没扣准**：
#   · 旧做法是整场采一次暗，而暗电平的漂移时间常数只有几个周期；
#   · 误差以 δ/(ln10·I₄) 进入斜率，4cm 越暗的通道放大越多；
#   · 810 的 4cm 恰好最暗，于是它最先、最严重地暴露出来。
# 这也解释了当初"找不到可回归的驱动量"——驱动量是时间，不是任何光学量。
#
# 固件加入每周期暗时隙后（2026-10-10），同一台设备在 B2 上实测 6 次：
#
#     810 偏离光谱趋势    −0.0293 ~ +0.0015   （旧数据：−0.33 ~ −0.88）
#     4cm 多收            1.00 ~ 1.07 倍      （旧数据：2.1 ~ 7.5 倍）
#
# 好了 20~300 倍，与其余三路同一量级。故恢复 810 进反演，四波长的
# 光谱残差自检自由度也从 1 回到 2。
#
# ⚠️ 目前只有 **B2 一个块**在新条件下验证过，而当初它在四个块上都异常。
#    采到其余块后要复核：若某块的 810 偏离再次超过 ±0.05，先查该次的
#    暗时隙是否正常（Take.dark_stats 的 std，实测地板 474/588），
#    不要直接归咎于光路。
#
# 下面这段是**旧固件时期**的记录，保留作对照：
# 810 的 4cm 读数里有 54%~87% 不是穿过体模的光。判据不是「G(810) 大」——
# 固定的增益失配给出常数 G，标定本来就能吸收；问题是它**不可重复**：
#
#     块        G(810)              块       G(670/770/850) 的块间离散
#     A3    −0.107 ± 0.0028         670          0.058
#     A4    −0.054 ± 0.0073         770          0.059
#     B3    −0.497 ± 0.0018         850          0.057
#     C2    −0.203 ± 0.0257         810        **0.198**  ← 21× 自身不确定度
#
# 已逐一排除：体模参数（810 距认证点 808 仅 2nm，插值误差 0.06%）、
# LED 装歪（反推等效距离 3.11~3.59cm 随块变，探头不会变）、环境光/贴合
# （与波长无关的通路应五路同抬，实测只有一路）、固件串台（I₄(810) 对任何
# 其他通道的比值离散 32%~66%）、解析错波长（会使 3cm/4cm 同向偏，实测反向）。
#
# 若将来又要退回三波长（670/770/850），代价已用在体数据核过 ——
# 同一份 10 人前额 TD-DOS 数据（见上方 950 一节）：
#
#     三波长 − 四波长，逐人配对：
#         直接拟实测 μa          +0.11 ± 0.17 %O₂（最大 0.35）
#         走完整设备流程          +0.22 ± 0.27 %O₂
#     相对 670~850nm 宽谱参考的逐人离散：四波长 1.02，三波长 1.09 %O₂
#     随机噪声放大 1.14 倍；条件数 3.19 → 3.64。
#     主要损失是自检：光谱残差自由度 2 → 1，能发现异常但分不清是哪一路。
#
# 也就是说：退回三波长对 TOI 影响很小，但会失去一半自检能力。
# 不要拿 950 顶替任何一路（水吸收，SO₂ 偏 +9.6）。
#
# ---------------------------------------------------------------------------
# 2026-10-12：**810 再次停用**，这一次的理由和 2026-10-10 那次完全不同。
#
# 这不是光路问题，是 4cm 探测通道上一个**非光学**的读数异常。
# 判据来自一次完全遮光的采集（黑电工胶带直接压住光学面，暗时隙回到
# −44,108/+7,821，与贴体模时一致，证明环境光已挡住）：
#
#     档位    670     770      810      850     950      （4cm，净值）
#      90     155     359      300      399     739      ← 全为零
#     130     357     263   69,885     −575    −934
#     150     228     369  124,833      494   1,159
#
# 挡死了光还有 12.5 万计数，就不是光；同时刻其余四路纹丝不动停在零上。
# std 只有 6,169~7,197（RSD 3%），是极稳的系统量，不是噪声。
# 幅度最大约为该通道正常信号（D4 档位 90 为 5,286）的 23 倍。
#
# 另有一次内部对照：黑纸压在 D4 上，810 在 3cm 读 −2,386（纸挡住了 810），
# 同一次 810 在 4cm 读 +43,080。纸既然挡得住 810，4cm 那 4.3 万就不是光。
#
# ⚠️ **不是干净的电流阈值。** 上面那次 43,080 发生在档位 90。所以现有证据
#    只支持「大驱动电流必触发」，不支持「小驱动电流必不发生」——
#    靠限制档位挡不住它，只能把这一路从反演里拿掉。
#
# 950 在同一次遮光采集中是干净的（−934 / +1,159）。此前怀疑过 950，
# 那是黑纸在长波半透所致，已排除。
#
# 代价（本次实测，见上方在体数据与 2026-10-12 的数值核算）：
#     读数偏移 −0.03 ± 0.02 %O₂（可被 k/b 吸收）
#     噪声放大 1.14×；对 G 误差的敏感度 0.503 → 0.653 %O₂/0.01
#     体模插值主导的总预算 ±4.28 → ±4.40 %O₂（+3%）——
#       因为 670 外推的 σG=0.0548 本来就压过其余三路之和
#
# 附带好处：B3 两次都采于 110 档，此前因 G(810)=+0.142（其余三路
# +0.32~+0.35）要整块剔除；810 拿掉后 B3 原样可用。
#
# ⚠️ 采集侧不要动：五个波长照常采、照常存档。三波长只是**反演**的选择，
#    保留 810 的原始记录，才能在 670/850 将来也出问题时有旁证，
#    也才能继续统计这个故障到底是阈值还是间歇。
# ---------------------------------------------------------------------------
# 2026-10-16：**850 停用**。机理与 810 同类（4cm 非光学分量），
# 只是此前被探头的寄生光垫高的真信号盖住了，探头优化后才暴露。
#
# 背景：2026-10-16 的「探头优化版」采集（6 块 A2/A3/A4/B2/B3/C2，各 1 次，
# 档位 255）证明原探头存在一条与体模光学性质无关的寄生光路，已被消除：
#     档位归一化后各块 670@3cm 的变化与 μeff 的相关 r = −0.804
#       （A2 μeff=0.913 → 0.90×；C2 μeff=1.805 → 0.07×）
#     实测/正演比值的块间跨度  3cm 11.7× → 1.8×，4cm 11.8× → 2.3×
#     斜率对理论的还原度 141.4%±9.5 → 84.2%±14.6（18 组中 16 组更接近）
#
# 真信号因此下降 5~14 倍，810/850/950 的固定非光学分量随即占了主导：
#
#     C2 的 4cm 净值    670    770      810      850      950
#                     2,995  12,898  372,460  128,432  447,009
#
# 810 比 770 高 29 倍，物理上不可能（两者在本体模的 μa 相近）。
#
# 850 失去跨块一致性 —— `850/770` 比值：
#     原探头   3cm 1.32~1.51    4cm 1.47~1.67    （跨块稳定）
#     优化后   3cm 1.29~3.12    4cm 1.42~9.96    （随块发散）
#
# 后果落到 G 上（同样 6 块，原探头 vs 优化后的块间离散）：
#     670   0.1184 → 0.0371   改善 3.19×
#     770   0.1056 → 0.0342   改善 3.09×
#     850   0.0982 → 0.1857   **变差 0.53×**
# 各块 G(850)：A2 −0.077、A3 −0.051、A4 −0.354、B2 −0.182、B3 −0.335、C2 −0.534
#
# 代价核算（蒙特卡洛，SO₂=70%）：
#                        平坦σ    波长相关σ    TOI 离散
#     优化版 670+770+850  0.0744    0.1158     ±14.29 %O₂
#     优化版 670+770      0.0351    0.0068     ± 1.77 %O₂
# 850 把误差推进了**波长相关**那一类 —— k/b 吸收不掉、代价最高的一类。
# 去掉它，TOI 离散降 8 倍，也比原探头三波长的 ±3.18 好 1.8 倍。
#
# ⚠️ 两条限定，不要当成定论：
#   (1) 只有 6 块、每块 1 次（dof=5），分不开「850 坏了」与「贴合变异」。
#       补满 12 块 × 3 次后必须重判。
#   (2) 结论与原探头**相反**：原数据里 850 是帮忙的（去掉它 TOI 离散
#       从 ±3.18 变 ±5.74）。所以这是探头改动带来的新状态，不是
#       「850 一直有问题」。换回旧探头时本条不适用。
#
# 待查：波长点亮顺序反转实验。若 810/850/950 的异常跟着顺序走，
#       即为时序/余辉污染，改固件可解，850 可恢复。
#
