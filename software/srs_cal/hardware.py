"""新硬件的几何与波长定义 —— 与 `config.py` 完全独立。

本包为 SRS 体模标定的**独立验证环境**，刻意不 import `config`：
`config.py` 描述的是现役 MBLL 产品线（850/810/770/730/700、D2=1.0 cm 短距），
与本硬件不是同一台机器。两边各自演进，互不牵连。

算法侧则**复用**已验证的 `fnirs_pipeline.srs` —— 该模块只 import `.mbll_core`，
波长 / 距离 / 增益 / k·b 全部通过 `SrsGeometry` 传参，不读 `config`，
所以在这里直接调用的就是产品代码本身，不是复制品。
"""

from __future__ import annotations

import numpy as np

# ---------------------------------------------------------------------------
# 光源
# ---------------------------------------------------------------------------
# 硬件实装五波长：670 / 770 / 810 / 850 / 950 nm。
#
# ⚠️ **950 nm 不进 SRS 反演**，只保留为质量/含水量参考通道。
#
#    依据是**在体实测**，不是文献估算 —— 取 10 名成人前额的时域 DOS 实测
#    μa(λ)（Zenodo 10.5281/zenodo.15828014，CC-BY 4.0），用本器件的四个
#    波长 670/770/810/850 拟纯 HbO/HbR 模型（与实际反演完全一致的配置），
#    再看各波长的残差 =（实测 − 纯血红蛋白预测）/ 实测：
#
#        670 nm   −0.1% ± 0.4%
#        770 nm   +0.3% ± 1.3%
#        810 nm   −0.5% ± 0.7%
#        850 nm   +0.2% ± 0.5%
#        950 nm  **+40.0% ± 2.5%**   ← 带外
#
#    四个在用波长上纯血红蛋白模型几乎完美（|残差| 均值 0.7%），
#    而 950 nm 有 40% 的吸收不是血红蛋白贡献（水 + 脂质）。
#
#    直接后果：同一批人、同一张消光表，
#        四波长 670/770/810/850        → SO₂ = 77.6 ± 3.6 %
#        五波长（加 950）              → SO₂ = 87.2 ± 3.1 %
#    **加入 950 使 SO₂ 偏高 +9.6 %O₂。**
#
#    `fnirs_pipeline/srs.py` 的 compute_toi() 文档串记录了同一机理：
#    「水与脂质吸收未建模…970nm 处水峰使 μa 从 0.157 升到 0.377」。
#
#    体模是干材料、不含水，950 nm 在体模上照常可测，采集时一并存档备查。
WAVELENGTHS_ALL_NM = np.array([670.0, 770.0, 810.0, 850.0, 950.0])
WAVELENGTHS_NM = np.array([670.0, 770.0, 810.0, 850.0])      # 设计上进反演的四路
WL_REFERENCE_ONLY_NM = np.array([950.0])                      # 仅作参考，不反演

# ---------------------------------------------------------------------------
# 810 nm：曾停用，2026-10-10 **恢复**
# ---------------------------------------------------------------------------
# 停用的原因后来证明是**误判**，记在这里以免重蹈。
#
# 当时（旧固件，无暗时隙）810 的 4cm 读数比"应有值"多 2.1~7.5 倍，
# 并据此排除了体模、几何、环境光、固件串台、解析错误，断定是硬件光路泄漏。
# **那个结论错了。** 真正的病因是**暗电平没扣准**：
#   · 旧做法是整场采一次暗，而暗电平的漂移时间常数只有几个周期；
#   · 误差以 δ/(ln10·I₄) 进入斜率，4cm 越暗的通道放大越多；
#   · 810 的 4cm 恰好最暗，于是它最先、最严重地暴露出来。
# 这也解释了当初"找不到可回归的驱动量"——驱动量是时间，不是任何光学量。
#
# 固件加入每周期暗时隙后（2026-10-10），同一台设备在 B2 上实测 6 次：
#
#     810 偏离光谱趋势    −0.0293 ~ +0.0015   （旧数据：−0.33 ~ −0.88）
#     4cm 多收            1.00 ~ 1.07 倍      （旧数据：2.1 ~ 7.5 倍）
#
# 好了 20~300 倍，与其余三路同一量级。故恢复 810 进反演，四波长的
# 光谱残差自检自由度也从 1 回到 2。
#
# ⚠️ 目前只有 **B2 一个块**在新条件下验证过，而当初它在四个块上都异常。
#    采到其余块后要复核：若某块的 810 偏离再次超过 ±0.05，先查该次的
#    暗时隙是否正常（Take.dark_stats 的 std，实测地板 474/588），
#    不要直接归咎于光路。
#
# 下面这段是**旧固件时期**的记录，保留作对照：
# 810 的 4cm 读数里有 54%~87% 不是穿过体模的光。判据不是「G(810) 大」——
# 固定的增益失配给出常数 G，标定本来就能吸收；问题是它**不可重复**：
#
#     块        G(810)              块       G(670/770/850) 的块间离散
#     A3    −0.107 ± 0.0028         670          0.058
#     A4    −0.054 ± 0.0073         770          0.059
#     B3    −0.497 ± 0.0018         850          0.057
#     C2    −0.203 ± 0.0257         810        **0.198**  ← 21× 自身不确定度
#
# 已逐一排除：体模参数（810 距认证点 808 仅 2nm，插值误差 0.06%）、
# LED 装歪（反推等效距离 3.11~3.59cm 随块变，探头不会变）、环境光/贴合
# （与波长无关的通路应五路同抬，实测只有一路）、固件串台（I₄(810) 对任何
# 其他通道的比值离散 32%~66%）、解析错波长（会使 3cm/4cm 同向偏，实测反向）。
#
# 若将来又要退回三波长（670/770/850），代价已用在体数据核过 ——
# 同一份 10 人前额 TD-DOS 数据（见上方 950 一节）：
#
#     三波长 − 四波长，逐人配对：
#         直接拟实测 μa          +0.11 ± 0.17 %O₂（最大 0.35）
#         走完整设备流程          +0.22 ± 0.27 %O₂
#     相对 670~850nm 宽谱参考的逐人离散：四波长 1.02，三波长 1.09 %O₂
#     随机噪声放大 1.14 倍；条件数 3.19 → 3.64。
#     主要损失是自检：光谱残差自由度 2 → 1，能发现异常但分不清是哪一路。
#
# 也就是说：退回三波长对 TOI 影响很小，但会失去一半自检能力。
# 不要拿 950 顶替任何一路（水吸收，SO₂ 偏 +9.6）。
WAVELENGTHS_ACTIVE_NM = np.array([670.0, 770.0, 810.0, 850.0])
WL_SUSPENDED_NM = np.array([])        # 无停用波长（950 另见上，本就不进反演）

# ---------------------------------------------------------------------------
# 探头几何
# ---------------------------------------------------------------------------
# 1 光源 + 2 长距探测器。取消短距，SSR 通路不适用于本硬件。
RHO_CM = np.array([3.0, 4.0])

# 组织折射率，进 Farrell-Patterson 边界条件
N_TISSUE = 1.4
# 体模折射率不在这里定义 —— 见 `phantom.REFRACTIVE_INDEX`（1.42，厂家
# 2026-10 书面答复）。这里原先写过 1.54（「环氧树脂」的教科书估值），
# 与厂家答复冲突，已删除：折射率只能有一个出处，否则两边各说各话。

# ---------------------------------------------------------------------------
# 反演默认参数（与 fnirs_pipeline.srs 的模块级常量保持一致，便于对照）
# ---------------------------------------------------------------------------
MUSP_REF_800 = 10.83        # μs′(800nm) cm⁻¹，成人前额 TD-DOS 人群均值
MUSP_EXPONENT = 0.932       # μs′ ∝ λ^(−b) 谱指数，人群均值
EXTINCTION_TABLE = "wray"   # 消光系数表

# ⚠️ wray 表与 Prahl 表在短波端差 30~45%（700/730 nm），670 nm 落在该区间内。
#    这一项误差随 SO₂ 变化（30% 时 +2.23，90% 时 +7.76 %O₂），
#    单点标定无效，须由血液体模降氧曲线的两参数线性修正 k·TOI+b 吸收。
#    详见 docs/SRS路线.md §7。


def geometry(gain_correction=None, k: float = 1.0, b: float = 0.0,
             wavelengths_nm=None, dark_level=None):
    """构造本硬件的 `SrsGeometry`。

    gain_correction : 体模矩阵标定产出的 G(λ)，斜率域加性修正
    k, b            : 降氧标定产出的两参数线性修正，未标定时为 1.0 / 0.0
    wavelengths_nm  : 参与反演的波长。默认 `WAVELENGTHS_NM`（设计中的四路）。
                      ⚠️ 810 当前停用（见本文件上方），在线/标定要显式传
                      `WAVELENGTHS_ACTIVE_NM`。
                      **默认值刻意保持为设计配置**：这个函数是共享的，
                      selftest 验的就是四波长设计，悄悄改默认会让它在
                      别处静默地换掉反演配置 —— 停用是运行期状态，
                      不是设计变更，该由调用方显式声明。
    dark_level      : (n_wl, n_rho) 暗电平。必须给 —— 实测 3cm 暗电平是
                      **负的** −43,981，不扣会让 log10(I₃/I₄) 整体偏。
    """
    from fnirs_pipeline.srs import SrsGeometry

    wl = WAVELENGTHS_NM if wavelengths_nm is None else wavelengths_nm
    return SrsGeometry(rho_cm=RHO_CM, wavelengths_nm=wl,
                       gain_correction=gain_correction,
                       dark_level=dark_level, k=k, b=b)
